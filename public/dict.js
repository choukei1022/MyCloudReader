const sChars = numS + stdS;
const tChars = numT + stdT;

// 状态控制
window.isTradMode = false;

// 👑 绝对安全的转换函数
window.toggleSimpTrad = function() {
    window.isTradMode = !window.isTradMode;
    
    // 生成 O(1) 的快速查找字典对象
    const fromDict = window.isTradMode ? sChars : tChars;
    const toDict = window.isTradMode ? tChars : sChars;
    
    const charMap = {};
    const safeLen = Math.min(fromDict.length, toDict.length);
    for (let i = 0; i < safeLen; i++) {
        charMap[fromDict[i]] = toDict[i];
    }

    // 遍历阅读区的文本节点并替换
    const walker = document.createTreeWalker(document.getElementById('content'), NodeFilter.SHOW_TEXT, null, false);
    let node;
    while (node = walker.nextNode()) {
        let text = node.nodeValue;
        let result = "";
        
        for (let i = 0; i < text.length; i++) {
            let char = text[i];
            // 👑 核心防御：如果在字典中找到了，就替换；如果没找到，或者出错，原样输出该字符，绝不产生 undefined！
            result += charMap[char] || char;
        }
        node.nodeValue = result;
    }
};